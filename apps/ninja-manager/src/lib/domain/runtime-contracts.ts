const deliveryIntegritySchema = z.object({
  canonicalization: z.literal(RUNTIME_CANONICALIZATION),
  payloadHash: sha256,
  semanticHash: sha256,
  envelopeHash: sha256,
}).strict();

export const deliveredReadOnlyCommandEnvelopeSchema = z.object({
  command: readOnlyCommandEnvelopeSchema,
  integrity: deliveryIntegritySchema,
}).strict().superRefine((value, context) => {
  const payloadHash = hashCanonicalPayload(value.command.payload);
  const semanticHash = commandSemanticHash(value.command);
  const envelopeHash = commandDeliveryEnvelopeHash(value.command, payloadHash, semanticHash);
  if (value.integrity.payloadHash !== payloadHash) {
    context.addIssue({
      code: "custom",
      message: "Delivered command payload hash mismatch",
      path: ["integrity", "payloadHash"],
    });
  }
  if (value.integrity.semanticHash !== semanticHash) {
    context.addIssue({
      code: "custom",
      message: "Delivered command semantic hash mismatch",
      path: ["integrity", "semanticHash"],
    });
  }
  if (value.integrity.envelopeHash !== envelopeHash) {
    context.addIssue({
      code: "custom",
      message: "Delivered command envelope hash mismatch",
      path: ["integrity", "envelopeHash"],
    });
  }
});

export type AgentEvent = z.infer<typeof agentEventSchema>;
export type RuntimeSnapshotEvent = z.infer<typeof runtimeSnapshotEventSchema>;
export type RuntimeObservationV2Event = z.infer<typeof runtimeObservationV2EventSchema>;
export type ProcessObservation = z.infer<typeof processObservationSchema>;
export type ReadOnlyCommandEnvelope = z.infer<typeof readOnlyCommandEnvelopeSchema>;
export type CommandAcknowledgement = z.infer<typeof commandAcknowledgementSchema>;
export type AcknowledgementStatus = z.infer<typeof acknowledgementStatusSchema>;
export type DeliveredReadOnlyCommandEnvelope = z.infer<typeof deliveredReadOnlyCommandEnvelopeSchema>;

export function runtimeStateVersion(value: { accounts: unknown; strategies: unknown }): string {
  return hashCanonicalPayload({ accounts: value.accounts, strategies: value.strategies });
}

export function eventEnvelopeHash(event: Omit<AgentEvent, "envelopeHash">): string {
  return hashCanonicalPayload(event);
}

export function commandSemanticHash(command: ReadOnlyCommandEnvelope): string {
  return hashCanonicalPayload({
    protocolVersion: command.protocolVersion,
    agentId: command.agentId,
    commandType: command.commandType,
    expectedStateVersion: command.expectedStateVersion,
    approvalId: command.approvalId,
    dryRun: command.dryRun,
    payload: command.payload,
  });
}

export function commandDeliveryEnvelopeHash(
  command: ReadOnlyCommandEnvelope,
  payloadHash = hashCanonicalPayload(command.payload),
  semanticHash = commandSemanticHash(command),
): string {
  return hashCanonicalPayload({
    command,
    integrity: {
      canonicalization: RUNTIME_CANONICALIZATION,
      payloadHash,
      semanticHash,
    },
  });
}

export function createDeliveredReadOnlyCommandEnvelope(
  input: ReadOnlyCommandEnvelope,
): DeliveredReadOnlyCommandEnvelope {
  const command = readOnlyCommandEnvelopeSchema.parse(input);
  const payloadHash = hashCanonicalPayload(command.payload);
  const semanticHash = commandSemanticHash(command);
  return deliveredReadOnlyCommandEnvelopeSchema.parse({
    command,
    integrity: {
      canonicalization: RUNTIME_CANONICALIZATION,
      payloadHash,
      semanticHash,
      envelopeHash: commandDeliveryEnvelopeHash(command, payloadHash, semanticHash),
    },
  });
}

export function acknowledgementHash(acknowledgement: CommandAcknowledgement): string {
  return hashCanonicalPayload(acknowledgement);
}

export function parseAgentEvent(input: unknown): AgentEvent {
  const event = agentEventSchema.parse(input);
  if (hashCanonicalPayload(event.payload) !== event.payloadHash) {
    throw new Error("Agent event payload hash does not match its contents");
  }
  const { envelopeHash, ...unsignedEnvelope } = event;
  if (eventEnvelopeHash(unsignedEnvelope) !== envelopeHash) {
    throw new Error("Agent event envelope hash does not match its contents");
  }
  return event;
}

export function parseRuntimeSnapshotEvent(input: unknown): RuntimeSnapshotEvent {
  const event = parseAgentEvent(input);
  if (event.eventType !== "runtime.snapshot") throw new Error("Expected a runtime snapshot event");
  return event;
}

export function parseRuntimeObservationV2Event(input: unknown): RuntimeObservationV2Event {
  const event = parseAgentEvent(input);
  if (event.eventType !== RUNTIME_OBSERVATION_V2_EVENT_TYPE) {
    throw new Error("Expected a runtime observation v2 event");
  }
  return event;
}

export function parseCommandAcknowledgement(input: unknown): CommandAcknowledgement {
  const acknowledgement = commandAcknowledgementSchema.parse(input);
  if (hashCanonicalPayload(acknowledgement.evidence) !== acknowledgement.evidenceHash) {
    throw new Error("Command acknowledgement evidence hash does not match its contents");
  }
  return acknowledgement;
}

export function parseDeliveredReadOnlyCommandEnvelope(input: unknown): DeliveredReadOnlyCommandEnvelope {
  return deliveredReadOnlyCommandEnvelopeSchema.parse(input);
}

const terminalStatuses = new Set<AcknowledgementStatus>([
  "rejected",
  "completed",
  "failed",
  "partial",
  "expired",
  "indeterminate",
]);

export function isTerminalAcknowledgement(status: AcknowledgementStatus): boolean {
  return terminalStatuses.has(status);
}

export function isAcknowledgementTransitionAllowed(
  currentStatus: string,
  nextStatus: AcknowledgementStatus,
): boolean {
  if (currentStatus === "queued") return ["accepted", "rejected", "expired"].includes(nextStatus);
  if (currentStatus === "accepted") {
    return ["started", "progress", "completed", "failed", "partial", "expired", "indeterminate"].includes(nextStatus);
  }
  if (currentStatus === "started" || currentStatus === "progress") {
    return ["progress", "completed", "failed", "partial", "expired", "indeterminate"].includes(nextStatus);
  }
  return false;
}
