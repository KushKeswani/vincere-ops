import { z } from "zod";

import { hashCanonicalPayload } from "./canonical-json";
import { runtimeObservationV2Schema } from "./runtime-observation-v2";

export { canonicalizeJsonForHash, hashCanonicalPayload } from "./canonical-json";

export const RUNTIME_PROTOCOL_VERSION = "1.0" as const;
export const MAX_COMMAND_TTL_MS = 10 * 60 * 1000;
export const RUNTIME_CANONICALIZATION = "RFC8785" as const;
export const RUNTIME_OBSERVATION_V2_EVENT_TYPE = "runtime.observation_v2" as const;

const sha256 = z.string().regex(/^sha256:[a-f0-9]{64}$/);
const stateVersion = sha256;
const safeSequence = z.number().int().safe().positive();
const isoTimestamp = z.iso.datetime({ offset: true });
const softwareVersion = z.string().regex(/^[A-Za-z0-9][A-Za-z0-9._+-]{0,39}$/);
const opaqueAccountRef = z.string().regex(
  /^acct_[a-z0-9]{16,64}$/,
  "Use the opaque account reference generated by the local agent",
);
const opaqueStrategyRef = z.string().regex(
  /^strat_[a-z0-9]{16,64}$/,
  "Use the stable strategy reference generated by the Add-On",
);
const maskedIdentifier = z.string().regex(
  /^\*{4,16}[A-Za-z0-9]{2,8}$/,
  "Only an ASCII mask plus the final account characters may leave the local agent",
);
const identifierFingerprint = z.string().regex(
  /^hmac-sha256:[a-f0-9]{64}$/,
  "Expected a keyed account fingerprint",
);

const processInstallationRef = z.string().regex(/^install_[a-z0-9]{16,64}$/);
const processRef = z.string().regex(/^process_[a-f0-9]{64}$/);

const processObservationBase = {
  observedAt: isoTimestamp,
  installationRef: processInstallationRef,
};

/**
 * Process-only evidence is intentionally carried by the existing authenticated heartbeat.
 * It never includes an executable path, PID, or other raw local process identity.
 */
export const processObservationSchema = z.discriminatedUnion("state", [
  z.object({
    ...processObservationBase,
    state: z.literal("running"),
    processStateVersion: stateVersion,
    processRef,
    matchedProcessCount: z.literal(1),
    unavailableReason: z.null(),
  }).strict(),
  z.object({
    ...processObservationBase,
    state: z.literal("not_running"),
    processStateVersion: stateVersion,
    processRef: z.null(),
    matchedProcessCount: z.literal(0),
    unavailableReason: z.null(),
  }).strict(),
  z.object({
    ...processObservationBase,
    state: z.literal("ambiguous"),
    processStateVersion: stateVersion,
    processRef: z.null(),
    matchedProcessCount: z.number().int().min(1).max(100),
    unavailableReason: z.enum([
      "MULTIPLE_ACTIVE_PROCESSES",
      "TRANSITIONAL_PROCESS_STATE",
    ]),
  }).strict().superRefine((value, context) => {
    if (value.unavailableReason === "MULTIPLE_ACTIVE_PROCESSES" && value.matchedProcessCount < 2) {
      context.addIssue({
        code: "custom",
        message: "Multiple-active evidence requires at least two matched processes",
        path: ["matchedProcessCount"],
      });
    }
    if (value.unavailableReason === "TRANSITIONAL_PROCESS_STATE" && value.matchedProcessCount !== 1) {
      context.addIssue({
        code: "custom",
        message: "Transitional evidence requires exactly one matched process",
        path: ["matchedProcessCount"],
      });
    }
  }),
  z.object({
    ...processObservationBase,
    state: z.literal("unknown"),
    processStateVersion: z.null(),
    processRef: z.null(),
    matchedProcessCount: z.null(),
    unavailableReason: z.enum([
      "OBSERVATION_FAILED",
      "OBSERVATION_TIME_INVALID",
    ]),
  }).strict(),
]);
const canonicalAccountRefs = z.array(opaqueAccountRef).max(500).refine(
  (values) => values.every((value, index) => index === 0 || values[index - 1] < value),
  "Account references must be unique and sorted",
);

export const runtimeAccountObservationSchema = z.object({
  accountRef: opaqueAccountRef,
  maskedIdentifier,
  identifierFingerprint,
  displayLabel: z.string().regex(/^(?:Simulation|Evaluation|Live|Unknown) account [1-9][0-9]{0,2}$/),
  accountType: z.enum(["simulation", "evaluation", "live", "unknown"]),
  connectionKind: z.enum(["simulation", "brokerage", "market_data", "unknown"]),
  connectionStatus: z.enum(["connected", "connecting", "disconnected", "unknown"]),
}).strict();

export const runtimeStrategyObservationSchema = z.object({
  strategyRef: opaqueStrategyRef,
  accountRef: opaqueAccountRef,
  displayLabel: z.string().regex(/^Strategy [1-9][0-9]{0,4}$/),
  strategyType: z.string().regex(/^[A-Za-z][A-Za-z0-9_.-]{0,79}$/),
  instrumentCode: z.string().regex(/^[A-Z]{1,6}(?: [A-Z]{3}[0-9]{2})?$/),
  timeframeCode: z.string().regex(/^(?:[1-9][0-9]{0,2} (?:Second|Minute|Day)|Tick|Range)$/),
  enabled: z.boolean(),
  sync: z.boolean().nullable(),
  runtimeState: z.enum(["disabled", "waiting_sync", "running", "error", "unknown"]),
  stateCode: z.enum([
    "SYNCHRONIZED",
    "AWAITING_SYNC",
    "AWAITING_CONNECTION",
    "DISABLED_BY_CONFIGURATION",
    "ERROR_REPORTED",
    "UNKNOWN",
  ]).nullable(),
}).strict().superRefine((value, context) => {
  if (value.runtimeState === "running" && (!value.enabled || value.sync !== true)) {
    context.addIssue({ code: "custom", message: "Running requires enabled=true and sync=true" });
  }
  if (!value.enabled && value.runtimeState !== "disabled" && value.runtimeState !== "unknown") {
    context.addIssue({ code: "custom", message: "A disabled strategy cannot report an active runtime state" });
  }
});

export const runtimeSnapshotPayloadSchema = z.object({
  source: z.literal("ninjatrader_addon"),
  collectionMode: z.enum(["authoritative_read_only", "supervised_simulation"]),
  complete: z.literal(true),
  observedAt: isoTimestamp,
  addonVersion: softwareVersion,
  stateVersion,
  accounts: z.array(runtimeAccountObservationSchema).max(500),
  strategies: z.array(runtimeStrategyObservationSchema).max(10_000),
}).strict().superRefine((value, context) => {
  const accountRefs = new Set(value.accounts.map((account) => account.accountRef));
  if (accountRefs.size !== value.accounts.length) {
    context.addIssue({ code: "custom", message: "Snapshot contains duplicate account references", path: ["accounts"] });
  }
  if (!value.accounts.every((account, index) => index === 0 || value.accounts[index - 1].accountRef < account.accountRef)) {
    context.addIssue({ code: "custom", message: "Snapshot accounts must be sorted by account reference", path: ["accounts"] });
  }
  const accountFingerprints = new Set(value.accounts.map((account) => account.identifierFingerprint));
  if (accountFingerprints.size !== value.accounts.length) {
    context.addIssue({ code: "custom", message: "Snapshot contains duplicate account fingerprints", path: ["accounts"] });
  }
  const strategyRefs = new Set(value.strategies.map((strategy) => strategy.strategyRef));
  if (strategyRefs.size !== value.strategies.length) {
    context.addIssue({ code: "custom", message: "Snapshot contains duplicate strategy references", path: ["strategies"] });
  }
  if (!value.strategies.every((strategy, index) => index === 0 || value.strategies[index - 1].strategyRef < strategy.strategyRef)) {
    context.addIssue({ code: "custom", message: "Snapshot strategies must be sorted by strategy reference", path: ["strategies"] });
  }
  value.strategies.forEach((strategy, index) => {
    if (!accountRefs.has(strategy.accountRef)) {
      context.addIssue({
        code: "custom",
        message: "Strategy references an account absent from the complete snapshot",
        path: ["strategies", index, "accountRef"],
      });
    }
  });
  if (value.stateVersion !== runtimeStateVersion(value)) {
    context.addIssue({
      code: "custom",
      message: "State version does not match the canonical runtime state",
      path: ["stateVersion"],
    });
  }
});

export const agentHeartbeatPayloadSchema = z.object({
  source: z.literal("vps_companion_agent"),
  observedAt: isoTimestamp,
  agentVersion: softwareVersion,
  health: z.enum(["online", "degraded"]),
  addonConnected: z.boolean(),
  addonVersion: softwareVersion.nullable(),
  pendingEventCount: z.number().int().min(0).max(100_000),
  processObservation: processObservationSchema.optional(),
}).strict().superRefine((value, context) => {
  if (
    value.processObservation
    && Date.parse(value.processObservation.observedAt) > Date.parse(value.observedAt)
  ) {
    context.addIssue({
      code: "custom",
      message: "Process observation cannot postdate its enclosing heartbeat",
      path: ["processObservation", "observedAt"],
    });
  }
});

