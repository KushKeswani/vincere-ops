const collectAccountCommandSchema = z.object({
  ...commandEnvelopeShape,
  commandType: z.literal("COLLECT_ACCOUNT_SNAPSHOT"),
  payload: z.object({
    accountRefs: canonicalAccountRefs,
  }).strict(),
}).strict();

const collectExecutionsCommandSchema = z.object({
  ...commandEnvelopeShape,
  commandType: z.literal("COLLECT_EXECUTIONS"),
  payload: z.object({
    accountRefs: canonicalAccountRefs,
    fromInclusive: isoTimestamp,
    toExclusive: isoTimestamp,
  }).strict(),
}).strict();

export const readOnlyCommandEnvelopeSchema = z.discriminatedUnion("commandType", [
  discoverRuntimeCommandSchema,
  collectAccountCommandSchema,
  collectExecutionsCommandSchema,
]).superRefine((value, context) => {
  const issuedAt = Date.parse(value.issuedAt);
  const expiresAt = Date.parse(value.expiresAt);
  if (expiresAt <= issuedAt) {
    context.addIssue({ code: "custom", message: "Command expiry must be after issue time", path: ["expiresAt"] });
  }
  if (expiresAt - issuedAt > MAX_COMMAND_TTL_MS) {
    context.addIssue({ code: "custom", message: "Command lifetime exceeds the ten-minute safety limit", path: ["expiresAt"] });
  }
  if (
    value.commandType === "COLLECT_EXECUTIONS"
    && Date.parse(value.payload.toExclusive) <= Date.parse(value.payload.fromInclusive)
  ) {
    context.addIssue({
      code: "custom",
      message: "Execution range end must be after its start",
      path: ["payload", "toExclusive"],
    });
  }
});

